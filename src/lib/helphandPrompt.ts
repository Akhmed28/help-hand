export function buildProactiveContext(opts: {
  activeFileName?: string;
  activeFileContent?: string;
  recentChanges?: string;
  errors?: string[];
  projectStructure?: string;
  conversationHistory?: string;
  generatedCode?: string;
  inactiveMinutes?: number;
  repeatedErrors?: { message: string; count: number }[];
  memoryContext?: string;
}) {
  const parts: string[] = [];

  // Inactivity signal — high priority trigger
  if (opts.inactiveMinutes && opts.inactiveMinutes >= 2) {
    parts.push(`⚠️ ПОЛЬЗОВАТЕЛЬ НЕАКТИВЕН ${opts.inactiveMinutes} минут (не отправлял сообщений и не генерировал код)`);
  }

  // Repeated errors — high priority trigger
  if (opts.repeatedErrors && opts.repeatedErrors.length > 0) {
    const lines = opts.repeatedErrors.map((e) => `"${e.message}" — повторилась ${e.count} раз`);
    parts.push(`⚠️ ПОВТОРЯЮЩИЕСЯ ОШИБКИ:\n${lines.join("\n")}`);
  }

  if (opts.generatedCode) {
    const truncated = opts.generatedCode.length > 8000
      ? opts.generatedCode.slice(0, 8000) + "\n... (обрезано)"
      : opts.generatedCode;
    parts.push(`ТЕКУЩИЙ КОД ПРОЕКТА:\n\`\`\`html\n${truncated}\n\`\`\``);
  }
  if (opts.recentChanges) {
    parts.push(`НЕДАВНИЕ ИЗМЕНЕНИЯ:\n${opts.recentChanges}`);
  }
  if (opts.errors && opts.errors.length > 0) {
    parts.push(`ТЕКУЩИЕ ОШИБКИ:\n${opts.errors.join("\n")}`);
  }
  if (opts.conversationHistory) {
    parts.push(`ИСТОРИЯ РАЗГОВОРА (последние сообщения):\n${opts.conversationHistory}`);
  }
  if (opts.memoryContext) {
    parts.push(opts.memoryContext);
  }

  return parts.join("\n\n---\n\n");
}
